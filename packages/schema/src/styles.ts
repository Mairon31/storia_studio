export const ANIMATION_STYLE_LIST: AnimationStylePreset[] = Object.values(ANIMATION_STYLE_PRESETS);

export function getAnimationStylePreset(styleId?: string): AnimationStylePreset {
  if (styleId && styleId in ANIMATION_STYLE_PRESETS) {
    return ANIMATION_STYLE_PRESETS[styleId as AnimationStyleId];
  }
  // Allow short code lookup ("A1", "B1", "B7", "B8", etc.)
  if (styleId) {
    const up = styleId.trim().toUpperCase();
    const byCode = ANIMATION_STYLE_LIST.find((s) => s.code.toUpperCase() === up || s.id.toUpperCase().startsWith(`${up}_`));
    if (byCode) return byCode;
  }
  return ANIMATION_STYLE_PRESETS.storia_editorial;
}
